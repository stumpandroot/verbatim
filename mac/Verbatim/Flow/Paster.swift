/// Puts text into the app you're using without losing what was on your clipboard.
///
/// The swap, as the best open-source dictation apps do it (Handy's receipt, VoiceInk's session tag):
/// 1. Check Accessibility first: without it ⌘V can't be pressed, so the paste is reported as failed, not done.
/// 2. Snapshot every clipboard item in every type (text, images, files, rich text).
/// 3. Put the dictation on the clipboard as a *promise* (`declareTypes(_:owner:)`), with markers that tell
///    clipboard managers to skip it (org.nspasteboard.TransientType, ConcealedType, AutoGeneratedType). The
///    text is handed over only when an app asks for it, and that request is the receipt that it was read.
/// 4. Press ⌘V in the target app, with the V key looked up in the current keyboard layout.
/// 5. Once the target has read the text and gone quiet for 200 ms, restore the snapshot, but only while the
///    clipboard's change count is still ours. If you copied something in between, your copy wins.
/// 6. No read within the app's limit (2.5 s, 5 s for remote desktops, Office, and Electron apps) means the
///    paste failed: the caller decides where the text goes (Dictate sends it to the thought pad).
/// Pastes run one at a time, so back-to-back dictations can't restore over each other.
@MainActor
enum Paster {
    private static let markers: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.TransientType"), .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.AutoGeneratedType"), .init("org.nspasteboard.source"),
    ]
    private static var chain: Task<Void, Never>?
    /// The receipt for the paste in progress, kept alive until it settles (the pasteboard asks it for the text).
    private static var current: PasteReceipt?

    /// How long the target must stay quiet after its last read before the old clipboard comes back. Some apps
    /// read more than once per paste (Chromium checks, then reads).
    private static let quiet: TimeInterval = 0.2

    enum Failure: Equatable {
        /// Accessibility isn't allowed, so ⌘V couldn't be pressed.
        case notTrusted
        /// ⌘V was pressed but no app read the clipboard in time.
        case notRead
        /// Typing stopped part way (a modifier key was pressed). Never retried: a retry could type the start twice.
        case typingInterrupted
    }

    enum Outcome: Equatable { case pasted, copiedOnly, failed(Failure) }

    /// What happens to the clipboard when a paste fails.
    enum OnFailure {
        /// The text stays on the clipboard so ⌘V works wherever you click next.
        case leaveOnClipboard
        /// The old clipboard comes back; the caller keeps the text somewhere else (the thought pad).
        case restoreClipboard
    }

    /// Whether the last paste that didn't land left its text on the clipboard. False when you copied something
    /// else before the target read it (your copy wins), or when the old clipboard came back.
    private(set) static var leftTextOnClipboard = false

    /// Pastes `text` into `target`. With no text field focused, leaves the text on the clipboard and returns `.copiedOnly`.
    /// With `keepOnClipboard` (Settings › Dictation › Also copy each dictation to the clipboard), a paste that lands
    /// leaves the text on the clipboard as an ordinary copy instead of putting the old clipboard back.
    static func paste(_ text: String, into target: NSRunningApplication?, focusedField: Bool, onFailure: OnFailure = .leaveOnClipboard,
                      keepOnClipboard: Bool = false) async -> Outcome {
        let previous = chain
        let task = Task { @MainActor () -> Outcome in
            _ = await previous?.value
            leftTextOnClipboard = false
            let out = await run(text, target: target, focusedField: focusedField, onFailure: onFailure, keep: keepOnClipboard)
            if out != .pasted, NSPasteboard.general.changeCount == lastWrite { leftTextOnClipboard = true }
            return out
        }
        chain = Task { _ = await task.value }
        return await task.value
    }

    /// The clipboard's change count right after Verbatim last wrote text to it as real data.
    private static var lastWrite = -1

    private static func run(_ text: String, target: NSRunningApplication?, focusedField: Bool, onFailure: OnFailure, keep: Bool) async -> Outcome {
        let pb = NSPasteboard.general
        guard AXIsProcessTrusted() else {
            Log.note("paste: Accessibility not allowed, ⌘V not pressed")
            if onFailure == .leaveOnClipboard { writeMarked(text, to: pb) }
            return .failed(.notTrusted)
        }
        guard focusedField else {
            // Nowhere to paste: keep the words on the clipboard so ⌘V works wherever you click next.
            writeMarked(text, to: pb)
            Log.note("paste: no focused field, left on clipboard")
            return .copiedOnly
        }

        if typesInstead(for: target) {
            let wait = activationWait(target)
            if let target, !target.isActive { target.activate() }
            if wait > 0 { try? await Task.sleep(nanoseconds: UInt64(wait * 1_000_000_000)) }
            if !fieldStillFocused(target) {
                writeMarked(text, to: pb)
                Log.note("paste: focus left the text field, left on clipboard")
                return .copiedOnly
            }
            switch await DirectTyper.type(text) {
            case .posted:
                Log.note("paste: typed \(text.count) chars")
                if keep { copy(text) }
                return .pasted
            case .partiallyPosted:
                Log.note("paste: typing interrupted part way; not retried")
                if onFailure == .leaveOnClipboard { writeMarked(text, to: pb) }
                return .failed(.typingInterrupted)
            case .notPosted:
                Log.note("paste: typing not posted, pasting instead")
            }
        }

        // The promise goes up before the app is brought forward, so a clipboard manager that reads every new
        // clipboard has done so before ⌘V; only reads after ⌘V count as the target's.
        let snapshot = snapshot(pb)
        let types: [NSPasteboard.PasteboardType] = [.string] + markers
        var receipt = PasteReceipt(text: text, markers: Set(markers))
        var change = pb.declareTypes(types, owner: receipt)
        current = receipt
        defer { current = nil }

        let wait = activationWait(target)
        if let target, !target.isActive { target.activate() }
        if wait > 0 { try? await Task.sleep(nanoseconds: UInt64(wait * 1_000_000_000)) }
        if !fieldStillFocused(target) {
            writeMarked(text, to: pb)
            Log.note("paste: focus left the text field, left on clipboard")
            return .copiedOnly
        }
        // Something read the text before ⌘V (a clipboard manager). The pasteboard keeps what it was given, so
        // the target's own read would never reach us. Put up a fresh promise.
        var legacy = false
        if receipt.anyRead {
            receipt = PasteReceipt(text: text, markers: Set(markers))
            change = pb.declareTypes(types, owner: receipt)
            current = receipt
            try? await Task.sleep(nanoseconds: 40_000_000)
            // Still read straight away: receipts can't be told apart here, so fall back to a timed hold.
            legacy = receipt.anyRead
            if legacy { Log.note("paste: clipboard read eagerly, using a timed hold") }
        }

        let injected = ProcessInfo.processInfo.systemUptime
        await pressCommandV()

        if legacy {
            try? await Task.sleep(nanoseconds: UInt64(timeout(for: target) * 1_000_000_000))
            if !receipt.lost, pb.changeCount == change { if keep { copy(text) } else { restore(snapshot, to: pb) } }
            return .pasted
        }

        let limit = timeout(for: target)
        // The pasteboard asks us for the text only on its first read and serves its own copy after that, so a
        // clipboard manager reading first could make the target's later read look settled. Always hold the text
        // a minimum time after ⌘V before restoring.
        let minHold: Double = limit > 2.5 ? 1.0 : 0.7
        var read = false
        while true {
            try? await Task.sleep(nanoseconds: 15_000_000)
            let now = ProcessInfo.processInfo.systemUptime
            if receipt.lost || pb.changeCount != change { break }
            if let last = receipt.lastRead(since: injected) {
                read = true
                if now - last >= quiet && now - injected >= minHold { break }
            }
            if now - injected >= limit { break }
        }
        if !read, receipt.lastRead(since: injected) != nil { read = true }
        let stillOurs = !receipt.lost && pb.changeCount == change
        let waited = String(format: "%.2f", ProcessInfo.processInfo.systemUptime - injected)
        if read {
            if stillOurs { if keep { copy(text) } else { restore(snapshot, to: pb) } }
            Log.note("paste: read by \(target?.bundleIdentifier ?? "front app") after ⌘V, settled in \(waited)s, restored=\(stillOurs)")
            return .pasted
        }
        guard stillOurs else {
            // You copied something else before the target read ours: leave your copy alone.
            Log.note("paste: clipboard changed before any read (\(waited)s); left as is")
            return .failed(.notRead)
        }
        switch onFailure {
        case .restoreClipboard: restore(snapshot, to: pb)
        case .leaveOnClipboard: writeMarked(text, to: pb)   // real data, so it outlives this paste's promise
        }
        Log.note("paste: no read within \(limit)s in \(target?.bundleIdentifier ?? "front app"); treated as failed")
        return .failed(.notRead)
    }

    /// Time for the target to come forward before ⌘V; none when it's already the active, frontmost app (or no
    /// target was given, so ⌘V goes to the front app as it is).
    private static func activationWait(_ target: NSRunningApplication?) -> Double {
        let front = NSWorkspace.shared.frontmostApplication?.processIdentifier
        let alreadyFront = target.map { $0.isActive && $0.processIdentifier == front } ?? true
        return DictationTiming.activationWait(alreadyFront: alreadyFront)
    }

    /// The field may have changed since the dictation started. Unknown (another app in front, no element
    /// exposed) counts as still focused.
    private static func fieldStillFocused(_ target: NSRunningApplication?) -> Bool {
        guard let pid = target?.processIdentifier ?? NSWorkspace.shared.frontmostApplication?.processIdentifier else { return true }
        return AppContext.focusedEditable(pid: pid) ?? true
    }

    // MARK: Timing per app

    private static let remoteApps: Set<String> = [
        "com.microsoft.rdc.macos", "com.microsoft.rdc.mac", "com.microsoft.rdc.osx.beta", "com.citrix.receiver.icaviewer.mac",
        "com.teamviewer.TeamViewer", "com.philandro.anydesk", "com.realvnc.vncviewer", "com.parallels.desktop.console",
        "com.vmware.fusion", "com.apple.ScreenSharing", "com.utmapp.UTM", "com.jumpdesktop.Jump-Desktop",
    ]
    private static let slowApps: Set<String> = [
        "com.microsoft.Word", "com.microsoft.Outlook", "com.microsoft.Excel", "com.microsoft.Powerpoint",
        "net.whatsapp.WhatsApp", "desktop.WhatsApp",
    ]
    private static let electronApps: Set<String> = [
        "com.tinyspeck.slackmacgap", "com.microsoft.VSCode", "com.hnc.Discord", "notion.id", "md.obsidian",
        "com.microsoft.teams2", "com.todesktop.230313mzl4w4u92", "com.figma.Desktop", "com.exafunction.windsurf",
    ]
    private static var electronCache: [String: Bool] = [:]

    /// How long to wait for the target to read the clipboard before calling the paste failed.
    private static func timeout(for app: NSRunningApplication?) -> TimeInterval {
        let id = app?.bundleIdentifier ?? ""
        if remoteApps.contains(id) || slowApps.contains(id) || isElectron(app) { return 5 }
        return 2.5
    }

    private static func isElectron(_ app: NSRunningApplication?) -> Bool {
        guard let app, let id = app.bundleIdentifier else { return false }
        if electronApps.contains(id) { return true }
        if let known = electronCache[id] { return known }
        let framework = app.bundleURL?.appendingPathComponent("Contents/Frameworks/Electron Framework.framework").path
        let yes = framework.map { FileManager.default.fileExists(atPath: $0) } ?? false
        electronCache[id] = yes
        return yes
    }

    // MARK: Type instead of paste

    static let typeEverywhereKey = "dictation.typeInsteadOfPaste"
    static let typeAppsKey = "dictation.typeInsteadOfPasteApps"

    /// Bundle IDs that get typed text instead of a paste (newline-separated in UserDefaults).
    static var typingApps: [String] {
        (UserDefaults.standard.string(forKey: typeAppsKey) ?? "").split(separator: "\n").map(String.init).filter { !$0.isEmpty }
    }

    private static func typesInstead(for app: NSRunningApplication?) -> Bool {
        if UserDefaults.standard.bool(forKey: typeEverywhereKey) { return true }
        guard let id = app?.bundleIdentifier else { return false }
        return typingApps.contains(id)
    }

    // MARK: Clipboard

    private typealias Snapshot = [[(NSPasteboard.PasteboardType, Data)]]

    private static func snapshot(_ pb: NSPasteboard) -> Snapshot {
        (pb.pasteboardItems ?? []).map { item in item.types.compactMap { t in item.data(forType: t).map { (t, $0) } } }
    }

    private static func restore(_ snapshot: Snapshot, to pb: NSPasteboard) {
        pb.clearContents()
        guard !snapshot.isEmpty else { return }
        let items: [NSPasteboardItem] = snapshot.map { pairs in
            let item = NSPasteboardItem()
            for (t, data) in pairs { item.setData(data, forType: t) }
            return item
        }
        pb.writeObjects(items)
    }

    /// The text as real clipboard data, with the markers clipboard managers skip.
    private static func writeMarked(_ text: String, to pb: NSPasteboard) {
        pb.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        for m in markers { item.setData(markerData(m), forType: m) }
        pb.writeObjects([item])
        lastWrite = pb.changeCount
    }

    nonisolated static func markerData(_ type: NSPasteboard.PasteboardType) -> Data {
        type.rawValue == "org.nspasteboard.source" ? Data((Bundle.main.bundleIdentifier ?? "Verbatim").utf8) : Data()
    }

    /// Re-copies text on purpose (History's Copy button): a normal clipboard write managers can keep.
    static func copy(_ text: String) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(text, forType: .string)
        lastWrite = pb.changeCount
    }

    // MARK: ⌘V in any keyboard layout

    static func pressCommandV() async {
        let key = keyCode(for: "v") ?? CGKeyCode(kVK_ANSI_V)
        let src = CGEventSource(stateID: .privateState)
        let cmd = CGKeyCode(kVK_Command)
        let events = [
            CGEvent(keyboardEventSource: src, virtualKey: cmd, keyDown: true),
            CGEvent(keyboardEventSource: src, virtualKey: key, keyDown: true),
            CGEvent(keyboardEventSource: src, virtualKey: key, keyDown: false),
            CGEvent(keyboardEventSource: src, virtualKey: cmd, keyDown: false),
        ]
        for (i, e) in events.enumerated() {
            e?.flags = (i == 3) ? [] : .maskCommand
            e?.post(tap: .cghidEventTap)
            try? await Task.sleep(nanoseconds: 8_000_000)
        }
    }

    /// The key that types `char` in the current layout. Layouts whose name ends in "⌘" (Dvorak – QWERTY ⌘)
    /// switch to QWERTY while Command is held, so they keep the ANSI key.
    private static func keyCode(for char: Character) -> CGKeyCode? {
        guard let source = TISCopyCurrentKeyboardLayoutInputSource()?.takeRetainedValue() else { return nil }
        if let namePtr = TISGetInputSourceProperty(source, kTISPropertyLocalizedName) {
            let name = Unmanaged<CFString>.fromOpaque(namePtr).takeUnretainedValue() as String
            if name.hasSuffix("⌘") { return CGKeyCode(kVK_ANSI_V) }
        }
        guard let ptr = TISGetInputSourceProperty(source, kTISPropertyUnicodeKeyLayoutData) else { return nil }
        let data = Unmanaged<CFData>.fromOpaque(ptr).takeUnretainedValue() as Data
        let target = String(char).lowercased()
        return data.withUnsafeBytes { raw -> CGKeyCode? in
            guard let layout = raw.baseAddress?.assumingMemoryBound(to: UCKeyboardLayout.self) else { return nil }
            for code in 0..<128 {
                var dead: UInt32 = 0
                var chars = [UniChar](repeating: 0, count: 4)
                var len = 0
                let status = UCKeyTranslate(layout, UInt16(code), UInt16(kUCKeyActionDown), 0, UInt32(LMGetKbdType()),
                                            OptionBits(1 << kUCKeyTranslateNoDeadKeysBit), &dead, chars.count, &len, &chars)
                if status == noErr, len > 0, String(utf16CodeUnits: chars, count: len).lowercased() == target { return CGKeyCode(code) }
            }
            return nil
        }
    }
}

/// The owner of a promised clipboard: the pasteboard asks it for the text when an app reads it, and that
/// request is the receipt. AppKit calls it on the main thread; the lock keeps the reads list safe regardless.
final class PasteReceipt: NSObject, NSPasteboardTypeOwner, @unchecked Sendable {
    private let lock = NSLock()
    private let text: String
    private let markers: Set<NSPasteboard.PasteboardType>
    private var reads: [TimeInterval] = []
    private var ownershipLost = false

    init(text: String, markers: Set<NSPasteboard.PasteboardType>) {
        self.text = text
        self.markers = markers
        super.init()
    }

    func pasteboard(_ sender: NSPasteboard, provideDataForType type: NSPasteboard.PasteboardType) {
        // A request for a marker is a clipboard manager checking whether to skip us, not a paste.
        if markers.contains(type) {
            sender.setData(Paster.markerData(type), forType: type)
            return
        }
        lock.lock(); reads.append(ProcessInfo.processInfo.systemUptime); lock.unlock()
        sender.setString(text, forType: type)
    }

    func pasteboardChangedOwner(_ sender: NSPasteboard) {
        lock.lock(); ownershipLost = true; lock.unlock()
    }

    var lost: Bool { lock.lock(); defer { lock.unlock() }; return ownershipLost }
    var anyRead: Bool { lock.lock(); defer { lock.unlock() }; return !reads.isEmpty }
    func lastRead(since t: TimeInterval) -> TimeInterval? {
        lock.lock(); defer { lock.unlock() }
        return reads.last { $0 >= t }
    }
}

/// Types text as keystrokes instead of pasting, for apps that block ⌘V. Unicode strings in chunks of 20
/// UTF-16 units on a neutral key (never splitting a surrogate pair), as VoiceInk does. Posting events doesn't
/// prove the app accepted them, and a partial attempt is never retried, because a retry could type text twice.
@MainActor
enum DirectTyper {
    enum Result { case posted, notPosted, partiallyPosted }

    private static let chunkSize = 20
    private static let chunksPerBatch = 16
    private static let modifiers: CGEventFlags = [.maskCommand, .maskControl, .maskAlternate, .maskShift]

    static func type(_ text: String) async -> Result {
        guard AXIsProcessTrusted(), let chunks = chunks(for: text), !chunks.isEmpty,
              let source = CGEventSource(stateID: .privateState) else { return .notPosted }
        // Wait briefly for held modifiers (the hotkey) to come up, or the chunks would arrive as shortcuts.
        let deadline = ProcessInfo.processInfo.systemUptime + 0.5
        while !CGEventSource.flagsState(.hidSystemState).intersection(modifiers).isEmpty {
            guard ProcessInfo.processInfo.systemUptime < deadline else { return .notPosted }
            try? await Task.sleep(nanoseconds: 10_000_000)
        }
        var posted = 0
        for chunk in chunks {
            // A modifier pressed mid-way means you're doing something else: stop.
            guard CGEventSource.flagsState(.hidSystemState).intersection(modifiers).isEmpty,
                  let down = CGEvent(keyboardEventSource: source, virtualKey: 0x31, keyDown: true),
                  let up = CGEvent(keyboardEventSource: source, virtualKey: 0x31, keyDown: false)
            else { return posted == 0 ? .notPosted : .partiallyPosted }
            // A line break rather than a new paragraph in rich editors.
            down.flags = chunk == [0x0D] ? .maskShift : []
            up.flags = []
            chunk.withUnsafeBufferPointer { buf in
                down.keyboardSetUnicodeString(stringLength: buf.count, unicodeString: buf.baseAddress)
            }
            down.post(tap: .cghidEventTap)
            up.post(tap: .cghidEventTap)
            posted += 1
            if posted % chunksPerBatch == 0, posted < chunks.count {
                try? await Task.sleep(nanoseconds: 1_000_000)
            }
        }
        return .posted
    }

    private static func chunks(for text: String) -> [[UniChar]]? {
        let normalized = text.replacingOccurrences(of: "\r\n", with: "\n").replacingOccurrences(of: "\r", with: "\n")
        var out: [[UniChar]] = []
        var buffer: [UniChar] = []
        for scalar in normalized.unicodeScalars {
            let v = scalar.value
            // Other control characters could act as editor commands; don't type them.
            if v < 0x20 || (0x7F...0x9F).contains(v) {
                guard v == 0x09 || v == 0x0A else { return nil }
                if !buffer.isEmpty { out.append(buffer); buffer.removeAll() }
                out.append([v == 0x0A ? 0x0D : 0x09])
                continue
            }
            let units = Array(String(scalar).utf16)
            if buffer.count + units.count > chunkSize { out.append(buffer); buffer.removeAll() }
            buffer.append(contentsOf: units)
        }
        if !buffer.isEmpty { out.append(buffer) }
        return out
    }
}

/// Settings › Dictate rows: type instead of paste, everywhere or in chosen apps.
struct PasteSettingsRows: View {
    @AppStorage(Paster.typeEverywhereKey) private var typeEverywhere = false
    @AppStorage(Paster.typeAppsKey) private var typeApps = ""

    private var apps: [String] { typeApps.split(separator: "\n").map(String.init).filter { !$0.isEmpty } }

    var body: some View {
        Toggle("Type instead of paste, in every app", isOn: $typeEverywhere)
        if !typeEverywhere {
            ForEach(apps, id: \.self) { id in
                HStack {
                    Text(Self.name(for: id))
                    Text(id).font(.system(size: 11, design: .monospaced)).foregroundStyle(Ink.mute).lineLimit(1)
                    Spacer()
                    Button { typeApps = apps.filter { $0 != id }.joined(separator: "\n") } label: { Image(systemName: "minus.circle") }
                        .buttonStyle(.plain).help("Paste in this app again")
                }
            }
            LabeledContent("Type instead of paste in") { Button("Add App…") { choose() }.buttonStyle(.settingsPill) }
        }
        Text("For apps that block ⌘V or paste the wrong thing. Typing leaves your clipboard alone but is slower, and if you press a key while it types, it stops rather than starting over.")
            .font(.system(size: 12)).foregroundStyle(Ink.mute)
    }

    private static func name(for id: String) -> String {
        guard let url = NSWorkspace.shared.urlForApplication(withBundleIdentifier: id) else { return id }
        return FileManager.default.displayName(atPath: url.path).replacingOccurrences(of: ".app", with: "")
    }

    private func choose() {
        let panel = NSOpenPanel()
        panel.canChooseFiles = true; panel.canChooseDirectories = false; panel.allowsMultipleSelection = false
        panel.allowedContentTypes = [.application]
        panel.directoryURL = URL(fileURLWithPath: "/Applications")
        panel.prompt = "Type in This App"
        guard panel.runModal() == .OK, let url = panel.url, let id = Bundle(url: url)?.bundleIdentifier, !apps.contains(id) else { return }
        typeApps = (apps + [id]).joined(separator: "\n")
    }
}
